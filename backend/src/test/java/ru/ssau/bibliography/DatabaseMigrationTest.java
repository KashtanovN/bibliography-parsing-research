package ru.ssau.bibliography;

import static org.assertj.core.api.Assertions.*;

import javax.sql.DataSource;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.*;

@SpringBootTest
class DatabaseMigrationTest {
  @DynamicPropertySource
  static void database(DynamicPropertyRegistry registry) {
    TestDatabase.configure(registry);
  }

  @Autowired DataSource dataSource;

  @Test
  void existingTableAndReviewedRulesSurviveAdoption() {
    var jdbc = new JdbcTemplate(dataSource);
    String schema = "legacy_migration_test";
    jdbc.execute("CREATE SCHEMA " + schema);
    try {
      jdbc.execute(
          "CREATE TABLE "
              + schema
              + ".bibliography_citationstandard (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY"
              + " KEY, key varchar(80) NOT NULL UNIQUE, label varchar(200) NOT NULL, version"
              + " varchar(40) NOT NULL, schema jsonb NOT NULL, updated_at timestamptz NOT NULL)");
      jdbc.update(
          "INSERT INTO "
              + schema
              + ".bibliography_citationstandard(key,label,version,schema,updated_at) VALUES"
              + " (?,?,?,?::jsonb,now())",
          StandardService.KEY,
          "Проверено библиотекой",
          "2.0",
          FormatterTest.SCHEMA.toString());
      var flyway =
          Flyway.configure()
              .dataSource(dataSource)
              .schemas(schema)
              .defaultSchema(schema)
              .baselineOnMigrate(true)
              .baselineVersion("0")
              .load();
      assertThat(flyway.migrate().migrationsExecuted).isEqualTo(1);
      assertThat(
              jdbc.queryForObject(
                  "SELECT label FROM " + schema + ".bibliography_citationstandard", String.class))
          .isEqualTo("Проверено библиотекой");
      assertThat(flyway.migrate().migrationsExecuted).isZero();
    } finally {
      jdbc.execute("DROP SCHEMA " + schema + " CASCADE");
    }
  }
}
